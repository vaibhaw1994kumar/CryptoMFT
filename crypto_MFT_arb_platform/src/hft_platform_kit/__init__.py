def _package_version() -> str:
    """Report the installed distribution version.

    Both public packages derive from distribution metadata so a release bump
    in ``pyproject.toml`` can never drift from what the runtime reports.
    """
    from importlib.metadata import PackageNotFoundError, version

    try:
        return version("hft-platform-kit")
    except PackageNotFoundError:  # pragma: no cover - source checkout
        return "0.3.0"


__version__ = _package_version()

